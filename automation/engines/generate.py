def _pillar_dirs() -> dict[str, str]:
    """Pillar display name -> md folder (generated by automation/curriculum.py)."""
    try:
        from ..core.taxonomy import PILLAR_DIRS

    except ImportError as exc:
        raise SystemExit(
            "automation/taxonomy.py is missing — run `python -m automation.curriculum` first."
        ) from exc
    return {name: f"md/{folder}" for name, folder in PILLAR_DIRS.items()}


