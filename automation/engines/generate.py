def _pid_alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


def _recorded_holder(path: Path) -> int | None:
    """Read the holder PID from the first line of a lock file."""
    try:
        first = path.read_text(encoding="ascii").splitlines()[0].strip()
        return int(first) if first.isdigit() else None
    except (OSError, ValueError, IndexError):
        return None


@contextlib.contextmanager
def pipeline_lock(path: Path = LOCK_PATH):
    """Prevent two pipeline instances from generating the same book twice.

    The lock file records the holder PID. OS-level locks release automatically
    when the holder process dies; the PID check additionally breaks a stale
    lock if the recorded holder is no longer alive, so long-running automation
    can always resume after crashes.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = None

    def _acquire() -> bool:
        nonlocal handle
        if sys.platform.startswith("win"):
            import msvcrt

            try:
                h = open(path, "a+b")
                if h.seek(0, os.SEEK_END) == 0:
                    h.write(b" ")
                    h.flush()
                h.seek(0)
                msvcrt.locking(h.fileno(), msvcrt.LK_NBLCK, 1)
            except OSError:
                if 'h' in locals():
                    h.close()
                return False
            try:
                h.seek(0)
                h.truncate()
                h.write(f"{os.getpid()}\n".encode("ascii"))
                h.flush()
            except OSError:
                pass
            handle = h
            return True
        else:
            import fcntl

            h = open(path, "w")
            try:
                fcntl.flock(h, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError:
                h.close()
                return False
            h.seek(0)
            h.write(f"{os.getpid()}\n")
            h.flush()
            handle = h
            return True

    def _release() -> None:
        nonlocal handle
        if handle is None:
            return
        try:
            if sys.platform.startswith("win"):
                import msvcrt

                handle.seek(0)
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
        except OSError:
            pass
        try:
            handle.close()
        except OSError:
            pass
        try:
            path.unlink()
        except OSError:
            pass
        handle = None

    acquired = False
    for attempt in range(3):
        if _acquire():
            acquired = True
            break
        holder = _recorded_holder(path)
        if holder is None or not _pid_alive(holder):
            try:
                path.unlink()
            except OSError:
                pass
            continue
        break
    if not acquired:
        holder = _recorded_holder(path)
        raise SystemExit(f"  ERROR: another pipeline instance is running (lock held by PID {holder}). {path}")
    try:
        yield
    finally:
        _release()


